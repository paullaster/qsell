#!/usr/bin/env bash
# Create (or verify) one installation's directory, secrets and runtime environment.
# Run on the host as the deploy user — NOT as root:
#   scripts/provision-instance.sh --config deploy/instances/new-shop.env
#
# Settings come from the config file or environment (see deploy/instance.env.example):
#   required: INSTANCE_ID  PUBLIC_DOMAIN  ADMIN_EMAIL
#   optional: APP_DIR DEPLOY_PATH EDGE_HTTP_PORT COMPOSE_PROJECT_NAME MEDIA_DRIVER
#             ADMIN_PASSWORD (otherwise prompted, or generated when not on a terminal)
#             EXTRA_ENV_FILE (KEY=VALUE lines appended: SMTP, payments, Cloudinary, ...)
#
# Safe to re-run: it never overwrites an existing .env.runtime or Postgres password,
# because changing the password after the database volume exists would lock the app out.
set -Eeuo pipefail
umask 077

here="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
source "$here/lib/instance-config.sh"

parse_common_args "$@"
((${#REST_ARGS[@]} == 0)) || die "Unknown argument(s): ${REST_ARGS[*]}"
[[ "${EUID}" -ne 0 ]] || die "Run as the deploy user, not root, so files have the right owner."

require_vars INSTANCE_ID PUBLIC_DOMAIN ADMIN_EMAIL
derive_defaults
validate_instance_settings
[[ "$ADMIN_EMAIL" =~ ^[^[:space:]@]+@[^[:space:]@]+\.[^[:space:]@]+$ ]] || die "ADMIN_EMAIL is not a valid email address."
command -v openssl >/dev/null || die "openssl is required."

secret_hex() { openssl rand -hex "$1"; }
secret_b64() { openssl rand -base64 "$1" | tr -d '\n'; }
# 32 random bytes, URL-safe base64 without padding (the format the app expects).
secret_key() { openssl rand -base64 32 | tr '+/' '-_' | tr -d '=\n'; }
env_quote() { printf "'%s'" "${1//\'/\\\'}"; }

info "Instance ${INSTANCE_ID} → ${DEPLOY_PATH} (${PUBLIC_DOMAIN})"
install -d -m 750 "$DEPLOY_PATH"
install -d -m 700 "$DEPLOY_PATH/secrets"

pw_file="$DEPLOY_PATH/secrets/postgres_password"
env_file="$DEPLOY_PATH/.env.runtime"

if [[ -s "$env_file" ]]; then
  info ".env.runtime already exists — leaving it untouched."
  [[ -s "$pw_file" ]] || die "$env_file exists but $pw_file is missing. Restore the password from your records; do not regenerate it."
else
  [[ ! -e "$pw_file" ]] || die "$pw_file exists without a matching .env.runtime. Remove it only if no database volume exists yet."
  db_password="$(secret_hex 24)"   # hex avoids URL-encoding problems in DATABASE_URL
  printf '%s' "$db_password" > "$pw_file"

  admin_password="${ADMIN_PASSWORD:-}"
  generated=0
  if [[ -z "$admin_password" ]]; then
    if [[ -t 0 ]]; then
      read -r -s -p "Initial admin password (16+ chars, blank to generate): " admin_password; echo
      if [[ -n "$admin_password" ]]; then
        read -r -s -p "Confirm: " confirm; echo
        [[ "$admin_password" == "$confirm" ]] || die "Passwords do not match."
      fi
    fi
    if [[ -z "$admin_password" ]]; then admin_password="$(secret_hex 12)"; generated=1; fi
  fi
  ((${#admin_password} >= 16)) || die "Admin password must be at least 16 characters."
  [[ "$admin_password" != *$'\n'* ]] || die "Admin password must be a single line."

  data_key="$(secret_key)"
  {
    echo "# Generated by scripts/provision-instance.sh on $(date -u +%FT%TZ). Mode 600; never commit."
    echo "NODE_ENV=production"
    echo "NEXT_PUBLIC_APP_URL=https://${PUBLIC_DOMAIN}"
    echo "AUTH_URL=https://${PUBLIC_DOMAIN}"
    echo "NEXTAUTH_URL=https://${PUBLIC_DOMAIN}"
    echo "DATABASE_URL=postgresql://qsell:${db_password}@db:5432/qsell"
    echo "AUTH_SECRET=$(secret_b64 48)"
    echo "JWT_SECRET=$(secret_b64 48)"
    # Losing these keys makes encrypted data (e.g. payment credentials) unreadable. Back them up.
    echo "DATA_ENCRYPTION_KEY=${data_key}"
    echo "PAYMENT_DATA_KEY=${data_key}"
    echo "SUPER_ADMIN_EMAIL=${ADMIN_EMAIL}"
    echo "SUPER_ADMIN_PASSWORD=$(env_quote "$admin_password")"
    echo "SUPER_ADMIN_NAME=Super Admin"
    echo "MEDIA_DRIVER=${MEDIA_DRIVER,,}"
    if [[ "${MEDIA_DRIVER,,}" == cloudinary ]]; then
      echo "CLOUDINARY_FOLDER=${INSTANCE_ID}"
      echo "# TODO: add CLOUDINARY_URL=cloudinary://KEY:SECRET@CLOUD_NAME (or the three CLOUDINARY_* parts)"
    fi
    if [[ -n "${EXTRA_ENV_FILE:-}" ]]; then
      [[ -f "$EXTRA_ENV_FILE" ]] || die "EXTRA_ENV_FILE not found: $EXTRA_ENV_FILE"
      echo "# --- appended from $(basename "$EXTRA_ENV_FILE") ---"
      cat "$EXTRA_ENV_FILE"
    fi
  } > "$env_file"
  chmod 600 "$env_file" "$pw_file"
  info "Created $env_file and $pw_file (mode 600)."
  if ((generated)); then
    echo "    Generated admin password (shown once; store it in a password manager):"
    echo "    ${admin_password}"
  fi
fi

# Verify what the deploy workflow will verify, so problems show up now.
db_url="$(sed -n 's/^DATABASE_URL=//p' "$env_file" | tail -n 1 | tr -d "'\"")"
case "$db_url" in *'@db:'*|*'@db/'*) ;; *) die "DATABASE_URL in $env_file must use host 'db'." ;; esac
driver="$(sed -n 's/^MEDIA_DRIVER=//p' "$env_file" | tail -n 1 | tr -d "'\"" | tr 'A-Z' 'a-z')"
case "${driver:-local}" in
  local) ;;
  cloudinary)
    if ! grep -Eq '^CLOUDINARY_URL=.+' "$env_file" \
       && ! { grep -Eq '^CLOUDINARY_CLOUD_NAME=.+' "$env_file" && grep -Eq '^CLOUDINARY_API_KEY=.+' "$env_file" && grep -Eq '^CLOUDINARY_API_SECRET=.+' "$env_file"; }; then
      echo "WARNING: MEDIA_DRIVER=cloudinary but credentials are missing in $env_file — the deploy will refuse until you add them." >&2
    fi ;;
  *) die "MEDIA_DRIVER '$driver' in $env_file is invalid (use local or cloudinary)." ;;
esac
[[ "$(stat -c %a "$env_file")" == 600 && "$(stat -c %a "$pw_file")" == 600 ]] || die "Secret files must be mode 600."

host_hint="${DEPLOY_HOST:-<IP or DNS name of this host>}"
user_hint="${DEPLOY_USER:-$(id -un)}"
cat <<DONE

Instance directory is ready: $DEPLOY_PATH
Set these in the GitHub Environment "$INSTANCE_ID" (scripts/configure-github-environment.sh does it for you):
  DEPLOY_HOST=$host_hint   DEPLOY_USER=$user_hint
  DEPLOY_PATH=$DEPLOY_PATH   COMPOSE_PROJECT_NAME=$COMPOSE_PROJECT_NAME
  PUBLIC_DOMAIN=$PUBLIC_DOMAIN   EDGE_HTTP_PORT=$EDGE_HTTP_PORT
Next: sudo scripts/setup-nginx-site.sh --config <file>   (TLS + Nginx), then run the deploy workflow.
DONE
